// Finishes the staff build (dist-staff/) for its own GitHub Pages repo and makes it an installable
// app: the custom domain, no Jekyll, no indexing, the web app manifest and icons, and a service
// worker that precaches the app shell only. Removes what only the customer site needs.
//
// Caching rule: the worker caches this build's own files and nothing else. Requests to any other
// origin (the API, storage, Google) are never intercepted, so no customer data is ever cached.
const crypto = require('node:crypto')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const out = path.join(root, 'dist-staff')
if (!fs.existsSync(path.join(out, 'index.html'))) throw new Error('build the staff site first')

fs.writeFileSync(path.join(out, 'CNAME'), 'staff.q3interiors.ie\n')
fs.writeFileSync(path.join(out, '.nojekyll'), '')
fs.writeFileSync(path.join(out, 'robots.txt'), 'User-agent: *\nDisallow: /\n')
fs.rmSync(path.join(out, 'og'), { recursive: true, force: true })

// Icons (rendered from the compact Q by npm run brand:images).
fs.mkdirSync(path.join(out, 'icons'), { recursive: true })
for (const file of fs.readdirSync(path.join(root, 'staff-pwa'))) {
  fs.copyFileSync(path.join(root, 'staff-pwa', file), path.join(out, 'icons', file))
}

const manifest = {
  name: 'Q3 Interiors Staff',
  short_name: 'Q3 Staff',
  description: 'Enquiries, appointments and settings for Q3 Interiors staff.',
  id: '/',
  start_url: '/',
  scope: '/',
  display: 'standalone',
  background_color: '#ffffff',
  // The staff header is white.
  theme_color: '#ffffff',
  icons: [
    { src: '/icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: '/icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    {
      src: '/icons/icon-maskable-512.png',
      sizes: '512x512',
      type: 'image/png',
      purpose: 'maskable',
    },
  ],
}
fs.writeFileSync(path.join(out, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2) + '\n')

// The app shell: every file of this build, except the pieces only GitHub or crawlers read and the
// .woff fallbacks every supported browser skips (woff2 is precached).
// version.json is never precached: an open app fetches it (no-store) to learn of a newer build.
const skip = new Set(['CNAME', '.nojekyll', 'robots.txt', 'sw.js', 'version.json'])
const files = []
const walk = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full)
    else {
      const rel = path.relative(out, full).split(path.sep).join('/')
      if (!skip.has(rel) && !rel.endsWith('.woff')) files.push(rel)
    }
  }
}
walk(out)
files.sort()
const hash = crypto.createHash('sha256')
for (const f of files) hash.update(f).update(fs.readFileSync(path.join(out, f)))
const version = hash.digest('hex').slice(0, 12)
const shell = ['/', ...files.map((f) => `/${f}`)]

// The build id an open app compares itself with: the file name of the staff app's own chunk
// (its hash changes with any staff code), read by src/staff-version.ts from import.meta.url.
const appChunk = fs.readdirSync(path.join(out, 'assets')).find((f) => /^StaffApp-.*\.js$/.test(f))
if (!appChunk) throw new Error('dist-staff has no StaffApp chunk')
fs.writeFileSync(
  path.join(out, 'version.json'),
  JSON.stringify({ app: appChunk, shell: version }) + '\n',
)

const worker = `// Generated by scripts/staff-site-files.cjs. Staff console service worker.
// Precaches this build's app shell only. Never touches other origins (API, storage, Google):
// those always go to the network, so no customer data is cached. The app is online-only.
const CACHE = 'q3-staff-shell-${version}'
const SHELL = ${JSON.stringify(shell)}

self.addEventListener('install', (event) => {
  // A new version takes over as soon as it is installed; the page offers a reload.
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(SHELL)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('q3-staff-shell-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return
  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return
  // Which build is live: always the network.
  if (url.pathname === '/version.json') return
  if (request.mode === 'navigate') {
    // Always try the network for the page, so a deploy shows at once; the cached shell only when
    // offline (the app then says so).
    event.respondWith(fetch(request).catch(() => caches.match('/index.html')))
    return
  }
  event.respondWith(caches.open(CACHE).then((cache) => cache.match(request, { ignoreSearch: true })).then((hit) => hit || fetch(request)))
})
`
fs.writeFileSync(path.join(out, 'sw.js'), worker)

console.log(
  `dist-staff: CNAME staff.q3interiors.ie, .nojekyll, robots.txt, manifest, icons, sw.js, version.json (${appChunk}; ${shell.length} shell files, ${version})`,
)
