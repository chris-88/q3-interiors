import type { FormDefinition } from './types.ts'
import { publishedForms } from './published.ts'

const TAG = '$form$'

export const PUBLISHED_SQL_PATH = 'supabase/forms/published.sql'

/** One `publish_form_version` call. Safe to re-run; the database rejects a changed schema. */
export function formVersionSql(form: FormDefinition): string {
  const json = JSON.stringify(form, null, 2)
  if (json.includes(TAG)) throw new Error(`Form ${form.formId} v${form.version} contains ${TAG}`)
  return `select public.publish_form_version(\n  '${form.formId}',\n  ${form.version},\n  ${TAG}${json}${TAG}::jsonb\n);\n`
}

export function publishedFormsSql(forms: FormDefinition[] = publishedForms): string {
  return [
    '-- Generated by `npm run forms:sql` from src/forms/published.ts. Do not edit by hand.',
    '-- Applied by scripts/db-migrate.sh after the migrations. Re-running it is a no-op.',
    '',
    ...forms.map(formVersionSql),
  ].join('\n')
}
